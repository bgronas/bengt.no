#!/usr/bin/env python3
"""Generate .pages.yml (Pages CMS configuration) from the policy files.

Category and tag choices come from data/taxonomy-policy.yaml and languages from
data/automation-policy.yaml, so the CMS can never offer a value the validator
would reject. `--check` fails when the checked-in file differs from what the
policy produces; CI runs it to catch drift.

The structure was verified against the Pages CMS documentation and upstream
source (pages-cms 2.1.8); the evidence is recorded in docs/cms.md.
"""

from __future__ import annotations

import argparse
import sys
from typing import Any

import yaml
from lib.common import LoadedPolicy, atomic_write, load_policy, run_cli

TARGET = ".pages.yml"
LANG_LABEL = {"no": "Norsk", "en": "English"}
DATE_FORMAT = "yyyy-MM-dd'T'HH:mm:ssxxx"

HEADER = """\
# Pages CMS configuration. GENERATED by scripts/sync_cms_schema.py from
# data/taxonomy-policy.yaml and data/automation-policy.yaml. Do not edit by hand:
# change the policy or the script, then run  ./publish.sh cms-sync
#
# Git is the source of truth. Pages CMS commits to this repository through its
# GitHub App; the same GitHub Actions workflow then processes the content.
# Saving in the CMS is a commit, not a deployment. See docs/cms.md.
"""


def _bool(name: str, label: str, description: str, default: bool = False) -> dict[str, Any]:
    return {"name": name, "label": label, "type": "boolean", "default": default, "description": description}


def taxonomy_fields(policy: LoadedPolicy) -> list[dict[str, Any]]:
    t = policy.p.taxonomy
    return [
        {
            "name": "categories",
            "label": "Taxonomy · Categories",
            "type": "select",
            "description": f"{t.categories_min} to {t.categories_max} categories. The list is defined in data/taxonomy-policy.yaml.",
            "options": {
                "multiple": True,
                "min": 0,
                "max": t.categories_max,
                "values": list(policy.taxonomy.categories),
            },
        },
        {
            "name": "tags",
            "label": "Taxonomy · Tags",
            "type": "select",
            "description": f"Up to {t.tags_max} canonical tags. A new tag must first be added to data/taxonomy-policy.yaml.",
            "options": {"multiple": True, "max": t.tags_max, "values": list(policy.taxonomy.tags.canonical)},
        },
        {
            "name": "series",
            "label": "Taxonomy · Series",
            "type": "string",
            "list": {"max": 1},
            "description": "Optional. One series name, written identically in every part.",
        },
        {
            "name": "series_order",
            "label": "Taxonomy · Part number in the series",
            "type": "number",
            "options": {"min": 1},
            "description": "Required when a series is set. Parts are ordered by this number.",
        },
    ]


