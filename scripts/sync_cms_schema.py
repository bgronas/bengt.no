def about_file(policy: LoadedPolicy, lang: str) -> dict[str, Any]:
    return {
        "name": f"about_{lang}",
        "label": f"About page ({LANG_LABEL.get(lang, lang)})",
        "type": "file",
        "path": f"{policy.p.content_roots[lang]}/about/index.md",
        "format": "yaml-frontmatter",
        "fields": [
            {"name": "title", "label": "Title", "type": "string", "required": True},
            {"name": "description", "label": "Description", "type": "text"},
            {"name": "body", "label": "Body (Markdown source)", "type": "code", "options": {"format": "markdown"}},
        ],
    }


def build_config(policy: LoadedPolicy) -> dict[str, Any]:
    langs = list(policy.p.languages)
    return {
        "media": [
            {
                "name": "intake",
                "label": "Intake media",
                "input": policy.p.intake_media_dir,
                "output": policy.p.intake_media_dir,
                "extensions": ["png", "jpg", "jpeg", "webp", "gif", "svg"],
                "rename": "safe",
            }
        ],
        "content": [
            *[intake_collection(policy, lang) for lang in langs],
            *[posts_collection(policy, lang) for lang in langs],
            *[about_file(policy, lang) for lang in langs],
        ],
        "settings": {"content": {"merge": True}},
        "actions": [
            {
                "name": "run-checks",
                "label": "Run checks",
                "workflow": "check.yml",
                "ref": "current",
                "confirm": False,
            },
            {
                "name": "process-and-deploy",
                "label": "Process drafts and deploy",
                "workflow": "deploy.yml",
                "cancelable": False,
                "confirm": {
                    "title": "Process drafts and deploy?",
                    "message": "Imports new articles, generates requested metadata and translations, and deploys every article that is not a draft.",
                    "button": "Run",
                },
            },
        ],
    }


def render(policy: LoadedPolicy) -> str:
    body = yaml.safe_dump(
        build_config(policy), sort_keys=False, allow_unicode=True, default_flow_style=False, width=1000
    )
    return HEADER + body


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if .pages.yml differs from the generated configuration"
    )
    args = parser.parse_args(argv)
    policy = load_policy()
    wanted = render(policy)
    target = policy.root / TARGET
    current = target.read_text(encoding="utf-8") if target.exists() else ""
    if args.check:
        if current != wanted:
            print(
                f"{TARGET} is out of date with the policy. Run ./publish.sh cms-sync and commit the result.",
                file=sys.stderr,
            )
            return 1
        print(f"{TARGET} matches the policy")
        return 0
    if current != wanted:
        atomic_write(target, wanted.encode("utf-8"))
        print(f"{TARGET} regenerated")
    else:
        print(f"{TARGET} already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(run_cli(main))
